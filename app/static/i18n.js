export const locales = { ru: 'ru-RU', en: 'en-GB', et: 'et-EE' };
export function normalizeLanguage(value) {
  return Object.hasOwn(locales, value) ? value : 'ru';
}
let language = 'ru';
try { language = normalizeLanguage(globalThis.localStorage?.getItem('spend-analyzer-language')); } catch { /* Storage may be blocked. */ }
export const getLanguage = () => language;
export const getLocale = () => locales[language];
export function setLanguage(value) {
  language = normalizeLanguage(value);
  try { globalThis.localStorage?.setItem('spend-analyzer-language', language); } catch { /* Selection still works in memory. */ }
}
export function t(key, params = {}) {
  const text = language === 'ru' ? key : messages[key]?.[language === 'en' ? 0 : 1] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => params[name] ?? match);
}
export const formatMoney = (amount, currency = 'EUR') => amount == null ? '—' : new Intl.NumberFormat(getLocale(), {
  style: 'currency', currency: currency || 'EUR', currencyDisplay: 'code', minimumFractionDigits: 2, maximumFractionDigits: 2,
}).format(amount);
export const formatDate = value => value ? new Intl.DateTimeFormat(getLocale()).format(new Date(value)) : '—';
export const formatPercent = value => new Intl.NumberFormat(getLocale(), { style: 'percent', maximumFractionDigits: 1 }).format(value / 100);
export function transactionCount(count) {
  const plural = new Intl.PluralRules(getLocale()).select(count);
  const labels = language === 'ru' ? { one: 'операция', few: 'операции', many: 'операций', other: 'операции' }
    : language === 'et' ? { one: 'tehing', other: 'tehingut' } : { one: 'transaction', other: 'transactions' };
  return `${new Intl.NumberFormat(getLocale()).format(count)} ${labels[plural] || labels.other}`;
}
export function translatePage(root = document) {
  root.documentElement.lang = language;
  root.title = t('Анализатор трат');
  root.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
  for (const attribute of ['title', 'placeholder', 'aria-label']) {
    root.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    });
  }
}
